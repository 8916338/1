  function lookup(s) {
    if (MAP[s]) return MAP[s];
    var low = LOWER[s.toLowerCase()];
    if (low) return low;
    var m = s.match(/^(.+?)(\s*[·(（]?\s*\d+\+?\)?)$/);
    if (m && (MAP[m[1]] || LOWER[m[1].toLowerCase()])) return (MAP[m[1]] || LOWER[m[1].toLowerCase()]) + m[2];
    var m2 = s.match(/^(.+?)([:：])$/);
    if (m2 && (MAP[m2[1]] || LOWER[m2[1].toLowerCase()])) return (MAP[m2[1]] || LOWER[m2[1].toLowerCase()]) + m2[2];
    for (var i = 0; i < RULES.length; i++) {
      if (RULES[i][0].test(s)) {
        var rep = RULES[i][1];
        return typeof rep === 'function' ? s.replace(RULES[i][0], rep) : s.replace(RULES[i][0], rep);
      }
    }
    return null;
  }

  function translateText(t) {
    var raw = t.nodeValue;
    if (!raw) return;
    var s = raw.trim();
    if (s.length < 2 || s.length > 200) return;
    var zh = lookup(s);
    if (!zh || zh === s) return;
    var lead = raw.match(/^\s*/)[0];
    var tail = raw.match(/\s*$/)[0];
    t.nodeValue = lead + zh + tail;
  }

  function inSkipArea(el) {
    try {
      return !!(el.closest && el.closest(SKIP_SELECTOR));
    } catch (e) {
      return false;
    }
  }

  function translateAttrs(root) {
    if (!root.querySelectorAll) return;
    var list;
    try {
      list = root.querySelectorAll('[title],[placeholder],[aria-label],[alt]');
    } catch (e) {
      return;
    }
    for (var i = 0; i < list.length; i++) {
      var el = list[i];
      if (inSkipArea(el)) continue;
      ['title', 'placeholder', 'aria-label', 'alt'].forEach(function (attr) {
        var v = el.getAttribute(attr);
        if (!v) return;
        var s = v.trim();
        if (!s || s.length > 200) return;
        var zh = lookup(s);
        if (zh && zh !== s) el.setAttribute(attr, zh);
      });
    }
  }

  function translate(root) {
    if (!root) return;
    if (root.nodeType === 3) {
      if (!skipNode(root)) translateText(root);
      return;
    }
    if (root.nodeType !== 1 && root.nodeType !== 9) return;
    try {
      var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode: function (n) {
          return skipNode(n) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
        }
      });
      var n;
      var guard = 0;
      while ((n = walker.nextNode())) {
        translateText(n);
        if (++guard > 8000) break;
      }
    } catch (e) {
    }
    translateAttrs(root);
  }

  function translateTitle() {
    try {
      var t = document.title;
      if (!t) return;
      var parts = t.split(' · ');
      var changed = false;
      for (var i = 0; i < parts.length; i++) {
        var zh = lookup(parts[i].trim());
        if (zh && zh !== parts[i]) {
          parts[i] = zh;
          changed = true;
        }
      }
      if (changed) document.title = parts.join(' · ');
    } catch (e) {
    }
  }

  var timer = null;
  var queue = [];
  function flush() {
    timer = null;
    var list = queue;
    queue = [];
    for (var i = 0; i < list.length; i++) {
      try {
        translate(list[i]);
      } catch (e) {
      }
    }
  }

  function observe() {
    if (!document.body) return;
    var obs = new MutationObserver(function (muts) {
      for (var i = 0; i < muts.length; i++) {
        var m = muts[i];
        if (m.type === 'characterData') {
          if (m.target && m.target.nodeType === 3) queue.push(m.target);
          continue;
        }
        if (m.type !== 'childList') continue;
        for (var j = 0; j < m.addedNodes.length; j++) {
          var n = m.addedNodes[j];
          if (n.nodeType === 1 || n.nodeType === 3) queue.push(n);
        }
      }
      if (!queue.length) return;
      if (timer) return;
      timer = setTimeout(flush, 240);
    });
    obs.observe(document.body, { childList: true, subtree: true, characterData: true });
  }

  var started = false;
  function run() {
    if (started || !document.body) return;
    started = true;
    translate(document.body);
    translateTitle();
    observe();
  }

  function later() {
    setTimeout(function () {
      translate(document.body);
    }, 60);
    setTimeout(translateTitle, 400);
  }

  run();
  document.addEventListener('DOMContentLoaded', run);
  window.addEventListener('load', run);
  var bootTimer = setInterval(function () {
    if (started) { clearInterval(bootTimer); return; }
    run();
  }, 300);

  ['turbo:load', 'turbo:render', 'pjax:end', 'page:load'].forEach(function (ev) {
    document.addEventListener(ev, later);
  });
  window.addEventListener('popstate', later);

  window.addEventListener('scroll', function () {
    if (timer) return;
    timer = setTimeout(function () {
      timer = null;
      translate(document.body);
      translateTitle();
    }, 400);
  }, { passive: true });
